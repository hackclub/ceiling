<h1 id="info-title">TEEN PARTICIPATION</h1>

<div id="info-text">
	<p>if you're a teenager aged 13-18 (inclusive) from anywhere in the world, you're eligible to receive ceiling merch and ceiling plushies for free - we'll pay for shipping, too!</p>

	<p>you can earn free stuff by <u>making and publishing personal technical projects</u> like websites, apps, or video games. everything you make remains entirely yours.</p>

	<p>here's how it works:</p>

	<ol>
	<li>install <a href="https://hackatime.hackclub.com/" target="_blank">hackatime</a> to track time spent coding</li>
	<li>work on your project, committing regularly to github to save your changes, and open source your code</li>
	<li>publish your project onto the internet for everyone to experience!</li>
	<li>once you release your project, you will earn ceiling tokens based on the number of hours you spent working on your project. (more specifics will be released once ceiling is launched.)</li>
	<li>trade your tokens for ceiling merch, which will be shipped to you for free. yay!</li>
	</ol>

	<p>after ceiling launch, tutorials will be released, as well as guides on setting up and installing everything needed. but if you're familiar with the process, you can start logging time from sep 11!</p>

	<p><b><i>making your project</i></b></p>
	<p><b>can i make multiple projects?</b> — yes, submitting multiple projects will let you combine the tokens you earn to get more expensive ceiling items!</p>
	<p><b>can i use ai to help with my project?</b> — yes, you may use ai to assist in any <u>technical</u> components in your project, such as debugging. you must state ai usage when submitting. excessive use of ai (producing "ai slop") may lead to a reduction in the tokens received or a rejection of your project. using ai-generated assets such as images or audio is strictly not allowed.</p>
	<p><b>is there any way to record time spent making assets?</b> — yes, you may use <a href="https://lapse.hackclub.com" target="_blank">lapse</a> to record time spent working on assets, such as drawing, animating, composing, producing sound effects, for up to 33% of the total time in the project. however, time spent researching, ideating, or making anything that does not directly appear in the final project will not be counted.</p>
	<p><b>can i submit something i made in the past?</b> - no, only time spent on your project since 11 sept, tracked with hackatime, will count. you may continue working on a project that you have previously worked on, but only the new time will be counted.</p>
	<p><b>what kind of projects can i make?</b> - any technical project that can be "shipped", ie. deployed and published on the internet for people to try for free without much technical experience. examples include: personal site hosted online, games published on itch.io or steam, app available for download on github releases. examples of things not allowed: a site made with wix (not technical), a html file (not shipped), a google drive file of game (not shipped).</p>

	<p>if you have more questions, reach out in <a href="https://hackclub.enterprise.slack.com/archives/C0AJLBLDM8E" target="_blank">#ceiling</a> on hack club slack to ask!</p>


</div>
